-- FXMind baseline schema. Portable between MySQL 8.4+ and H2 (MODE=MySQL) used by fast tests.
-- All timestamps are stored in UTC.

CREATE TABLE currency (
    ID      BIGINT      NOT NULL AUTO_INCREMENT,
    NAME    VARCHAR(20) NOT NULL,
    ENABLED BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_CURRENCY PRIMARY KEY (ID),
    CONSTRAINT UK_CURRENCY_NAME UNIQUE (NAME)
);

CREATE TABLE symbol (
    ID              BIGINT       NOT NULL AUTO_INCREMENT,
    NAME            VARCHAR(50)  NOT NULL,
    DESCRIPTION     VARCHAR(500),
    BASE_CURRENCY   VARCHAR(10)  NOT NULL,
    QUOTE_CURRENCY  VARCHAR(10)  NOT NULL,
    DISABLED        BOOLEAN      NOT NULL DEFAULT FALSE,
    TRACK_SENTIMENT BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_SYMBOL PRIMARY KEY (ID),
    CONSTRAINT UK_SYMBOL_NAME UNIQUE (NAME)
);

CREATE TABLE site (
    ID          BIGINT       NOT NULL AUTO_INCREMENT,
    NAME        VARCHAR(50)  NOT NULL,
    DESCRIPTION VARCHAR(255),
    CONSTRAINT PK_SITE PRIMARY KEY (ID),
    CONSTRAINT UK_SITE_NAME UNIQUE (NAME)
);

CREATE TABLE news_event (
    ID             BIGINT       NOT NULL AUTO_INCREMENT,
    CURRENCY_ID    BIGINT       NOT NULL,
    HAPPEN_TIME    DATETIME(6)  NOT NULL,
    NAME           VARCHAR(500) NOT NULL,
    IMPORTANCE     TINYINT      NOT NULL,
    ACTUAL_VALUE   VARCHAR(127),
    FORECAST_VALUE VARCHAR(127),
    PREVIOUS_VALUE VARCHAR(127),
    PARSED_AT      DATETIME(6)  NOT NULL,
    RAISED         BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT PK_NEWS_EVENT PRIMARY KEY (ID),
    CONSTRAINT FK_NEWS_EVENT_CURRENCY FOREIGN KEY (CURRENCY_ID) REFERENCES currency (ID)
);
CREATE INDEX IX_NEWS_EVENT_HAPPEN_TIME ON news_event (HAPPEN_TIME);
CREATE INDEX IX_NEWS_EVENT_DEDUP ON news_event (CURRENCY_ID, HAPPEN_TIME, IMPORTANCE);

CREATE TABLE open_position_ratio (
    ID          BIGINT      NOT NULL AUTO_INCREMENT,
    SYMBOL_ID   BIGINT      NOT NULL,
    SITE_ID     BIGINT      NOT NULL,
    PARSED_AT   DATETIME(6) NOT NULL,
    LONG_RATIO  DOUBLE      NOT NULL,
    SHORT_RATIO DOUBLE      NOT NULL,
    CONSTRAINT PK_OPEN_POSITION_RATIO PRIMARY KEY (ID),
    CONSTRAINT FK_OPR_SYMBOL FOREIGN KEY (SYMBOL_ID) REFERENCES symbol (ID),
    CONSTRAINT FK_OPR_SITE FOREIGN KEY (SITE_ID) REFERENCES site (ID)
);
CREATE INDEX IX_OPR_SYMBOL_TIME ON open_position_ratio (SYMBOL_ID, PARSED_AT);

CREATE TABLE person (
    ID                      BIGINT         NOT NULL AUTO_INCREMENT,
    EMAIL                   VARCHAR(255)   NOT NULL,
    PASSWORD_HASH           VARCHAR(100)   NOT NULL,
    PRIVILEGE               VARCHAR(20)    NOT NULL,
    BALANCE                 DECIMAL(19, 4) NOT NULL DEFAULT 0,
    SUBSCRIPTION_EXPIRES_AT DATETIME(6),
    ACTIVATION_TOKEN        VARCHAR(64),
    ACTIVATED               BOOLEAN        NOT NULL DEFAULT FALSE,
    REGISTERED_AT           DATETIME(6)    NOT NULL,
    REGISTRATION_IP         VARCHAR(45),
    CONSTRAINT PK_PERSON PRIMARY KEY (ID),
    CONSTRAINT UK_PERSON_EMAIL UNIQUE (EMAIL),
    CONSTRAINT UK_PERSON_ACTIVATION_TOKEN UNIQUE (ACTIVATION_TOKEN)
);

CREATE TABLE settings (
    ID            BIGINT       NOT NULL AUTO_INCREMENT,
    NAME          VARCHAR(255) NOT NULL,
    SETTING_VALUE TEXT,
    DEFAULT_VALUE TEXT,
    DESCRIPTION   TEXT,
    CONSTRAINT PK_SETTINGS PRIMARY KEY (ID),
    CONSTRAINT UK_SETTINGS_NAME UNIQUE (NAME)
);

CREATE TABLE jobs (
    ID                 BIGINT        NOT NULL AUTO_INCREMENT,
    GRP                VARCHAR(255)  NOT NULL,
    NAME               VARCHAR(255)  NOT NULL,
    HANDLER            VARCHAR(100)  NOT NULL,
    CRON               VARCHAR(128)  NOT NULL,
    DESCRIPTION        VARCHAR(1000),
    LAST_STATUS        TEXT,
    PREVIOUS_FIRE_TIME DATETIME(6),
    NEXT_FIRE_TIME     DATETIME(6),
    ENABLED            BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_JOBS PRIMARY KEY (ID),
    CONSTRAINT UK_JOBS_GROUP_NAME UNIQUE (GRP, NAME)
);
